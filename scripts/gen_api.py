#!/usr/bin/env python3
"""Generate lib/api/openapi-types.ts and lib/api/endpoints.ts from the OpenAPI yaml.

Usage: python3 scripts/gen_api.py path/to/ShopSafeNG_API.yaml
Needs: PyYAML. Re-run whenever the backend spec changes.
"""
import re
import sys
from pathlib import Path

import yaml

spec = yaml.safe_load(open(sys.argv[1]))
SCHEMAS = spec["components"]["schemas"]
OUT = Path(__file__).resolve().parent.parent / "lib" / "api"
HEADER = "/* AUTO-GENERATED by scripts/gen_api.py from the OpenAPI spec. Do not edit by hand. */\n"
IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")


def key(k):
    return k if IDENT.match(k) else repr(k)


def lit(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    return '"' + str(v).replace("\\", "\\\\").replace('"', '\\"') + '"'


def ts(s, ref_prefix=""):
    """OpenAPI schema -> TS type string."""
    if s is None or s == {}:
        return "unknown"
    if "$ref" in s:
        return ref_prefix + s["$ref"].split("/")[-1]
    t = None
    if "allOf" in s:
        parts = [ts(x, ref_prefix) for x in s["allOf"]]
        t = parts[0] if len(parts) == 1 else " & ".join(f"({p})" for p in parts)
    elif "oneOf" in s or "anyOf" in s:
        t = " | ".join(f"({ts(x, ref_prefix)})" for x in s.get("oneOf") or s["anyOf"])
    elif "enum" in s:
        t = " | ".join(lit(v) for v in s["enum"] if v is not None) or "never"
    else:
        ty = s.get("type")
        if ty == "string":
            t = "File | Blob" if s.get("format") == "binary" else "string"
        elif ty in ("integer", "number"):
            t = "number"
        elif ty == "boolean":
            t = "boolean"
        elif ty == "array":
            inner = ts(s.get("items"), ref_prefix)
            t = f"({inner})[]" if re.search(r"[|&]", inner) else f"{inner}[]"
        elif ty == "object" or "properties" in s or "additionalProperties" in s:
            props = s.get("properties") or {}
            req = set(s.get("required") or [])
            lines = []
            for name, ps in props.items():
                opt = "" if name in req else "?"
                ro = "readonly " if ps.get("readOnly") else ""
                lines.append(f"  {ro}{key(name)}{opt}: {ts(ps, ref_prefix)};")
            ap = s.get("additionalProperties")
            if ap is not None and ap is not False:
                lines.append(f"  [k: string]: {'unknown' if ap is True else ts(ap, ref_prefix)};")
            t = "{\n" + "\n".join(lines) + "\n}" if lines else "Record<string, unknown>"
        else:
            t = "unknown"
    if s.get("nullable"):
        t = f"{t} | null"
    return t


# ---------- openapi-types.ts ----------
out = [HEADER]
for name, sch in SCHEMAS.items():
    body = ts(sch)
    if body.startswith("{"):
        out.append(f"export interface {name} {body}\n")
    else:
        out.append(f"export type {name} = {body};\n")
(OUT / "openapi-types.ts").write_text("\n".join(out))


# ---------- endpoints/<area>.ts ----------
def camel(s):
    p = s.split("_")
    return p[0] + "".join(x.title() for x in p[1:])


def has_binary(s, seen=()):
    if isinstance(s, dict):
        if s.get("format") == "binary":
            return True
        r = s.get("$ref")
        if r:
            n = r.split("/")[-1]
            return n not in seen and has_binary(SCHEMAS[n], seen + (n,))
        return any(has_binary(v, seen) for v in s.values())
    if isinstance(s, list):
        return any(has_binary(v, seen) for v in s)
    return False


EP = OUT / "endpoints"
EP.mkdir(exist_ok=True)

(EP / "_shared.ts").write_text(
    HEADER
    + """export type Query = Record<string, string | number | boolean | undefined | null>;

/** Build multipart FormData from a plain object (File/Blob, arrays and scalars). */
export function toFormData(obj: object): FormData {
  const fd = new FormData();
  for (const [k, v] of Object.entries(obj as Record<string, unknown>)) {
    if (v === undefined || v === null) continue;
    const add = (x: unknown) => fd.append(k, x instanceof Blob ? x : String(x));
    Array.isArray(v) ? v.forEach(add) : add(v);
  }
  return fd;
}

export const enc = (v: string | number) => encodeURIComponent(String(v));
"""
)

areas = {}
seen_names = set()
for path, item in spec["paths"].items():
    common = item.get("parameters", [])
    for method, o in item.items():
        if method == "parameters":
            continue
        opid = o["operationId"]
        base = opid[4:] if opid.startswith("api_") else opid
        group = base.split("_")[0]
        rest = base.split("_")[1:]
        if group.startswith("social"):
            rest = [group[len("social"):]] + rest
            group = "social"
        fname = camel("_".join(rest))
        if (group, fname) in seen_names:
            raise SystemExit(f"duplicate name {group}.{fname}")
        seen_names.add((group, fname))

        params = common + o.get("parameters", [])
        pathp = [p for p in params if p["in"] == "path"]
        queryp = [p for p in params if p["in"] == "query"]

        args = [f"{camel(p['name'])}: string" for p in pathp]
        rb = o.get("requestBody")
        multipart = False
        if rb:
            content = rb["content"]
            jsch = (content.get("application/json") or next(iter(content.values()))).get("schema")
            multipart = has_binary(jsch)
            bt = ts(jsch, "S.")
            if multipart:
                bt = f"{bt} | FormData"
            args.append(f"body{'' if rb.get('required') else '?'}: {bt}")
        undocumented_body = False
        if not rb and method in ("post", "put", "patch"):
            # Spec documents no body here (drf-spectacular gap); still let callers send one.
            args.append("body?: Record<string, unknown>")
            undocumented_body = True
        if not queryp:
            # Spec documents no query params; allow ad-hoc ones (pagination, ?id=, ...).
            args.append("query?: Query")
        else:
            qfields = [
                f"{key(p['name'])}{'' if p.get('required') else '?'}: {ts(p.get('schema'), 'S.')}"
                for p in queryp
            ]
            any_req = any(p.get("required") for p in queryp)
            args.append(f"query{'' if any_req else '?'}: {{ {'; '.join(qfields)} }}")
        args = [a for a in args if "?:" not in a] + [a for a in args if "?:" in a]

        ok = next((c for c in ("200", "201", "202", "204") if c in o["responses"]), None)
        rt = "void"
        if ok:
            rc = o["responses"][ok].get("content")
            if rc:
                rt = ts(next(iter(rc.values())).get("schema"), "S.")

        url = path
        for p in pathp:
            url = url.replace("{" + p["name"] + "}", "${enc(" + camel(p["name"]) + ")}")
        url_expr = f"`{url}`"
        cfg_s = ", { params: query }"
        summary = (o.get("summary") or "").replace("*/", "")
        doc = f"  /** {method.upper()} {path} - {summary} */"

        if method in ("get", "delete"):
            call = f"apiClient.{method}<{rt}>({url_expr}{cfg_s})"
        else:
            if rb:
                b = "body instanceof FormData ? body : toFormData(body)" if multipart else "body"
                if multipart and not rb.get("required"):
                    b = "body === undefined || body instanceof FormData ? body : toFormData(body)"
            else:
                b = "body" if undocumented_body else "undefined"
            call = f"apiClient.{method}<{rt}>({url_expr}, {b}{cfg_s})"
        areas.setdefault(group, []).append(
            f"{doc}\n  {fname}: async ({', '.join(args)}): Promise<{rt}> =>\n    (await {call}).data,\n"
        )

for area, fns in areas.items():
    uses_form = any("toFormData" in f for f in fns)
    src = [
        HEADER,
        "import apiClient from '../config';",
        "import type * as S from '../openapi-types';",
        f"import {{ enc{', toFormData' if uses_form else ''}, type Query }} from './_shared';",
        "",
        f"export const {area}Api = {{",
        "\n".join(fns),
        "} as const;\n",
    ]
    (EP / f"{area}.ts").write_text("\n".join(src))

(EP / "index.ts").write_text(
    HEADER
    + "".join(f"import {{ {a}Api }} from './{a}';\n" for a in areas)
    + "\nexport const api = {\n"
    + "".join(f"  {a}: {a}Api,\n" for a in areas)
    + "} as const;\n\nexport { toFormData } from './_shared';\n"
)
print(f"{sum(len(v) for v in areas.values())} operations, {len(SCHEMAS)} schemas, areas: {', '.join(areas)}")


# ---------- slash-routes.ts (used by app/api/[...path]/route.ts) ----------
slash = sorted({p for p in spec["paths"] if p.startswith("/api/") and p.endswith("/")})
rx = ["^" + re.sub(r"\\\{[^}]+\\\}", "[^/]+", re.escape(p[:-1])) + "$" for p in slash]
body = ",\n".join("  /" + r.replace("/", "\\/") + "/" for r in rx)
(OUT / "slash-routes.ts").write_text(
    HEADER + "/** /api routes that the backend only serves WITH a trailing slash. */\n"
    "export const SLASH_ROUTES: RegExp[] = [\n" + body + ",\n];\n"
)
